#include<stdio.h>
int main(void){
    char ac[] ={1,2,3,4,5,6,7,8,9,};
    char *p = ac;
    printf("p =%p\n",p);//p =00000031919ffc2f 十六进制基数：0~9，A=10，B=11，C=12，D=13，E=14，F=15 2f转换成十进制=47
    printf("p+1 =%p\n",p+1);//p+1 =00000031919ffc30 sizeof(char)=1 30十六进制转换成十进制=48 
    int ai[] ={1,2,3,4,5,6,7,8,9,};
    int *q = ai;
    printf("q =%p\n",q);//q =000000772ebffb00  
    printf("q+1 =%p\n",q+1);

    // 指针 +1 不是加 1 个字节，而是加【一个元素的大小】—— 大小由指针的类型决定
// char* 加 1 字节，int* 加 4 字节（sizeof(int)=4），所以 p+1 刚好指向下一个元素
    printf("ac[1]  = %d\n", ac[1]);
// 数组写法：取第 1 个元素

    printf("*(p+1) = %d\n", *(p+1));
    // ac 是【首元素的地址】，p = ac 就是把那个地址交给 p（这叫"数组名退化成指针"）
// *(p+1)：先算 p+1（往后挪 1 个 char = 1 字节），再解引用 → 得到 ac[1] = 2
// 括号不能省！*p+1 是"先取值(*p)再加 1"，和 *(p+1) 完全不是一回事
    printf("*(ac+2)= %d\n", *(ac+2));
    // *(ac+2)：ac 是【地址】，+2 往后挪 2 个元素 → 到 ac[2] 的位置，再 * 取值 = 3
// 注意区分：ac 是地址，*ac 是值（= ac[0] = 1）。带不带 * 差一层
    return 0;
}