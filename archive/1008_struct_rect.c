/* ============================================================
   结构体练习 5：矩形
   ============================================================

   【这题练什么】
   把这几节课的东西串起来：
     · 结构体定义 + typedef（类型定义）
     · 结构体【嵌套】结构体
     · 值传递 vs 指针传递
     · 函数返回结构体
     · const 参数

   【要用的两个类型】

   typedef struct { int x, y; } point;      // 一个点
   typedef struct {
       point p1;        // 左上角
       point p2;        // 右下角
   } Rect;                                   // 一个矩形

   ★ typedef 是什么意思
     typedef struct { ... } point;   写完这一行以后，
     声明变量就可以直接写   point p;   —— 不用再写 struct 了。
     （STM32 里的 GPIO_InitTypeDef 就是这么来的）

   ★ 嵌套结构体的成员怎么访问
     一层一层往外点：
         r.p1.x     ← 先到 r 的 p1，再到 p1 的 x
         r->p1.x    ← 如果 r 是【指针】，开头用 ->

   ============================================================
   第 1 步：先不用函数
   ============================================================
   1. 写出上面两个类型（point 和 Rect）
   2. 在 main 里定义一个 Rect，叫 r
        r.p1 = {0, 0}      （左上角）
        r.p2 = {4, 3}      （右下角）
   3. 打印一行：  Rect: (0,0) - (4,3)

   提示：嵌套成员用两层点，比如 r.p1.x

   ============================================================
   第 2 步：值传递
   ============================================================
   写一个函数：

       void printpoint(point p)      // 注意：参数【不带】*

   把 "打印一个点" 这段搬进去，在 main 里这样调用：

       printpoint(r.p1);
       printpoint(r.p2);

   ★ 想一想：这里为什么【不用】写 & ？

   我的答案：因为不是指针 所以不用写 就是 函数的声明不带* 所以要值 就写r.p1这种类型

   【标准答案】printpoint 的参数类型是 point（【不带】*），说明它要的是【值】。
              所以直接写变量或成员就行：printpoint(r.p1);
              什么时候才要写 & ？—— 参数类型【带】* 的时候。
              判断标准只有这一条：看声明里的参数类型有没有 *。

   ============================================================
   第 3 步：指针传递（要能改到原件）
   ============================================================
   写一个函数：

       void movepoint(point *p, int dx, int dy)

   它把 p 指向的那个点移动：x 加 dx，y 加 dy。

   在 main 里：
       movepoint(&r.p1, 10, 10);      // 注意 & 和 . 的先后
       printpoint(r.p1);              // 应该变成 (10,10)

   ★ 对比第 2 步：为什么这个函数【必须】用指针？

   我的答案:因为这里函数声明了一个指向结构体的指针 所以需要用到取地址 

   【标准答案】因为 movepoint 要【改到原件】。
              如果参数写成 point p（值传递），函数里改的是【复印件】，
              main 里的 r.p1 一点都不会变 —— 第 2 步的 printpoint 就是这种情况。
              只有传【地址】，函数才能顺着地址改到 main 里那个点。
              ★ 注意区分：
                 你答的"因为声明是指针，所以要取地址"——那是【结果】（怎么写调用）。
                 题目问的是【原因】——为什么要把它设计成指针：因为要改原件。

   ============================================================
   第 4 步：const 指针
   ============================================================
   写一个函数：

       int area(const Rect *r)        // 返回矩形面积

   面积 = (右下角x - 左上角x) × (右下角y - 左上角y)

   提示：r 是【指针】，访问嵌套成员要写 r->p1.x

   ★ const 在这里是什么意思？

   我的答案：给一个只读的指针指向的值 不能做修改 

   【标准答案】const 表示"这个指针【指向的内容】是只读的"。
              area 只需要读 r->p1 和 r->p2 来算面积，不会改它们，
              所以用 const 把这件事声明出来。
              好处：万一函数里手滑写了 r->p1.x = 0，编译器会立刻报错拦住你。
              ★ 注意：不是"指针本身只读"，是"它【指向的东西】只读"。

   ============================================================
   第 5 步（选做）：函数返回结构体
   ============================================================
   写一个函数：

       point makepoint(int x, int y)   // 造一个点，返回出去

   在 main 里：
       r.p1 = makepoint(1, 1);
       printpoint(r.p1);               // 应该打印 (1,1)

   ★ 这个函数返回的是【值】（不是指针），
     所以函数里写：  point p;  p.x = x;  p.y = y;  return p;
     注意：返回值和 struct4.c 里的 getStruct 不一样 —— 那个返回的是指针。

   ============================================================
   验收
   ============================================================
   · gcc -Wall struct5.c -o struct5.exe    零警告
   · 每一步的输出都对
   · 三个「我的答案」都填了

   卡住就告诉我：卡在第几步、哪一行、报什么错。
   ============================================================ */

#include <stdio.h>

typedef struct
{
    int x,y;
}point;

typedef struct
{
    point p1;
    point p2;
}Rect;

void printpoint(point p)
{
      printf("(%d,%d)\n", p.x, p.y);
}
void movepoint(point *p, int dx, int dy)
{
    p->x = p->x + dx;
    p->y = p->y + dy;
}
int area(const Rect *p)
{
    return (p->p2.x - p->p1.x )*(p->p2.y - p->p1.y);
}
point makepoint(int x, int y)
{
    point p;
    p.x = x;  p.y = y;
    return p;    
} 
int main(void)
{
    Rect r;

    r.p1.x = 2;
    r.p1.y = 3;
    r.p2.x = 6;
    r.p2.y = 8;
    
    point a = makepoint(1, 2);       
    printpoint(a);      
    printf("%d\n", area(&r)) ;
    movepoint(&r.p1,5,10);
    printpoint(r.p1);
    
    return 0;
}
//写法	      是什么	       里面怎么写
// point p;	 结构体变量         p.x
// point *q = &p;	指针，指向 p	q->x
// void f(point p)	参数是值（拷一份）	p.x
// void f(point *q)	参数是指针（给地址）	q->x
// 调用 f(p)	给值	
// 调用 f(&p)	给地址	
// point f(void)	返回一个结构体	return p;
// point *f(void)	返回一个指针	return &p; ← 危险，别返回局部变量的地址