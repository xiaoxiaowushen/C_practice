#include <stdio.h>
int main()
{
    int n;
    scanf("%d",&n);              // 输入几行，九九乘法表就输 9

    int i,j;                     // i = 行号，j = 这一行里的第几个式子

    i = 1;                       // 从第 1 行开始
    while(i <= n){               // 一共要打 n 行

        j = 1;                   // ★ 关键：每换一行，j 必须回到 1
                                 //   写在【外层循环里面、内层循环前面】
                                 //   只写这一次！内层里绝不能再写

        while(j <= i){           // 第 i 行有 i 个式子：1*i 2*i ... i*i

            printf("%d*%d=%d", j, i, j*i);   // 先打印，此时 j、i 都还是"没加过"的值

            if(j*i < 10){        // 结果是 1 位数（比如 1*3=3）→ 补 3 个空格
                printf("   ");
            }else{               // 结果是 2 位数（比如 3*4=12）→ 补 2 个空格
                printf("  ");    //   两种加起来都是 8 格宽，所以能对齐
            }

            j++;                 // ★ 干完活再加：内层循环的【最后一行】，在 } 上面
        }                        // ← 内层循环结束 = 这一行打完了

        printf("\n");            // ★ 换行！没有这句，所有式子会挤成一长条
                                 //   位置：在内层循环【外面】、外层循环【里面】

        i++;                     // ★ 换下一行：外层循环的【最后一行】，在 } 上面
    }                            // ← 外层循环结束

    return 0;
}
