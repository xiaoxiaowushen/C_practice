/* ============================================================
   位运算示例：用位控制 8 个 LED
   ============================================================

   ★ 这是【示例代码】。看懂之后，请合上它自己写一遍 bits1.c。

   把一个 int 想成一块【8 个开关的面板】：

       第7格 第6格 第5格 第4格 第3格 第2格 第1格 第0格
       LED7  LED6  LED5  LED4  LED3  LED2  LED1  LED0

   每一格的值：  1   2   4   8   16  32  64  128
                （每往左一格，值乘 2 —— 也就是 2 的 n 次方）

   state = 0b00001001  →  LED3 和 LED0 开着，其他关着

   ============================================================ */

#include <stdio.h>

/* ------------------------------------------------------------
   把第 n 格【打开】
   ------------------------------------------------------------
   参数：
     state   指向外面那块面板（传地址，才能改到原件）
     n       要打开第几格

   做法分两步：
     ① 1 << n        造一个"模板"：只有第 n 格是开着的
     ② *state | 模板  把模板合并到当前面板上

   为什么 | 能打开某一格？
     | 的规则是"只要有一边是开，合并后就是开"
     所以模板上开着的那一格，会把面板对应的那格也【顶成开】
     其他格：和 0 做或 = 原样不变

   举例（state = 0, n = 3）：
     *state  =  0000 0000
     1 << 3  =  0000 1000      ← 只有第 3 格开着
     或起来  =  0000 1000      = 8
   ------------------------------------------------------------ */
void led_on(int *state, int n)
{
    *state = *state | (1 << n);
    /*      └──┬──┘
            *state 就是外面那块面板本身 */
}

/* ------------------------------------------------------------
   把第 n 格【关上】
   ------------------------------------------------------------
   做法分三步：
     ① 1 << n       造出"只有第 n 格开着"的模板
     ② ~ 取反        变成"只有第 n 格关着，其他全开着"
     ③ & 上去        把那一格压成 0

   为什么 & 能关掉某一格？
     & 的规则是"只要有一边是关，结果就是关"
     所以模板上关着的那一格，会把面板对应的那格也【压成关】
     其他格：和 1 做与 = 原样不变

   举例（*state = 10111111, n = 3）：
     *state       1011 1111
     & ~(1 << 3)  1111 0111      ← ~(1<<3)，只有第 3 位是 0
                  ─────────
                  1011 0111      ← 第 3 位从 1 变成了 0 ✓

   逐位看：
     1 & 1 = 1      两根都是开的，还是开
     1 & 0 = 0      ★ 这一位被压关了
     0 & 0 = 0

   ★ ~ 不能省！写成 *state &= (1 << n) 就变成"只保留第 n 位"了
   ------------------------------------------------------------ */
void led_off(int *state, int n)
{
    *state = *state & ~(1 << n);
}

/* ------------------------------------------------------------
   第 n 格开着吗？开着返回 1，关着返回 0
   ------------------------------------------------------------
   做法分两步：
     ① state >> n    把【整个面板】右移 n 位，让第 n 格挪到最右边
     ② & 1           只看最右边那一格，其他全屏蔽掉

   ★ 注意：移位是【整体】移动，不是一格一格挪

   举例（state = 0000 1000，只有第 3 格开着）：
     n = 1:  0000 1000 >> 1 = 0000 0100,  再 & 1 = 0    ← 第 1 格关着
     n = 3:  0000 1000 >> 3 = 0000 0001,  再 & 1 = 1    ← 第 3 格开着 ★

   ★ 这个函数【不收指针】—— 它只读、不修改，所以给个值就够了
     （要不要用指针，就看"要不要改到原件"）
   ------------------------------------------------------------ */
int led_is_on(int state, int n)
{
    return (state >> n) & 1;
}

/* ------------------------------------------------------------
   把 8 格的状态打印出来给你看
   ------------------------------------------------------------
   从第 7 格打到第 0 格（高位在左边，和寄存器手册写法一致）

   循环里每一轮做的事：
     state >> i    把第 i 格挪到最右边
     & 1           取出来，得到 0 或 1
   ------------------------------------------------------------ */
void led_show(int state)
{
    int i;
    for(i = 7; i >= 0; i--){               /* 从高位往低位走 */
        printf("%d ", (state >> i) & 1);   /* 取出第 i 格打印 */
    }
    printf("\n");
}

/* ------------------------------------------------------------
   main：验证
   ------------------------------------------------------------ */
int main(void)
{
    int state = 0;              /* 状态变量：0 = 8 格全关 */

    printf("全部熄灭:    ");
    led_show(state);            /* 0 0 0 0 0 0 0 0 */

    led_on(&state, 0);          /* 打开第 0 格 */
    led_on(&state, 3);          /* 打开第 3 格 */
    printf("点亮 0 和 3: ");
    led_show(state);            /* 0 0 0 0 1 0 0 1 */

    /* led_is_on 返回 1 或 0，? : 拿去选 "ON" 还是 "OFF" */
    printf("LED3 是 %s\n", led_is_on(state, 3) ? "ON" : "OFF");
    printf("LED1 是 %s\n", led_is_on(state, 1) ? "ON" : "OFF");

    led_off(&state, 0);         /* 关掉第 0 格 */
    printf("熄灭 LED0 后: ");
    led_show(state);            /* 0 0 0 0 1 0 0 0 */

    return 0;
}

